@Composable
fun ComposeEmptyActivityTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    // 主题设置由 ThemeController 内存状态驱动（首次从 SharedPreferences 加载）
    ThemeController.init(context)
    // 深色模式：0=跟随系统，1=浅色，2=深色
    val isDark = when (ThemeController.darkMode) {
        1 -> false
        2 -> true
        else -> darkTheme
    }
    val colorScheme = when {
        // 动态色彩：Android 12+ 从系统壁纸取色
        ThemeController.colorMode == 0 && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (isDark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        // 自定义种子色（预选色 / 颜色卡自选）：基于种子色生成完整 Material3 方案
        ThemeController.colorMode == 2 -> seedColorScheme(ThemeController.seedColor, isDark)
        // 默认蓝色（低版本动态色彩不可用时也回退到这里）
        isDark -> darkScheme
        else -> lightScheme
    }

    val view = LocalView.current
    if (!view.isInEditMode) SideEffect {
        (view.context as? android.app.Activity)?.window?.let { window ->
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !isDark
                isAppearanceLightNavigationBars = !isDark
            }
            window.navigationBarColor = colorScheme.background.toArgb()
        }
    }
    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}

/** 基于公开 Compose Color API 生成稳定的种子色主题，避免依赖 Material 内部受限接口。 */
@Composable
private fun seedColorScheme(seedArgb: Long, dark: Boolean): androidx.compose.material3.ColorScheme {
    return remember(seedArgb, dark) {
        val seed = Color(seedArgb)
        val neutral = Color(
            red = (seed.red + seed.green + seed.blue) / 3f,
            green = (seed.red + seed.green + seed.blue) / 3f,
            blue = (seed.red + seed.green + seed.blue) / 3f
        )
        if (dark) {
            darkScheme.copy(
                primary = blend(seed, Color.White, 0.34f),
                onPrimary = blend(seed, Color.Black, 0.72f),
                primaryContainer = blend(seed, Color.Black, 0.48f),
                onPrimaryContainer = blend(seed, Color.White, 0.78f),
                secondary = blend(seed, neutral, 0.45f).let { blend(it, Color.White, 0.28f) },
                secondaryContainer = blend(seed, Color.Black, 0.62f),
                inversePrimary = blend(seed, Color.Black, 0.22f)
            )
        } else {
            lightScheme.copy(
                primary = blend(seed, Color.Black, 0.18f),
                onPrimary = Color.White,
                primaryContainer = blend(seed, Color.White, 0.78f),
                onPrimaryContainer = blend(seed, Color.Black, 0.72f),
                secondary = blend(seed, neutral, 0.48f).let { blend(it, Color.Black, 0.20f) },
                secondaryContainer = blend(seed, Color.White, 0.84f),
                inversePrimary = blend(seed, Color.White, 0.32f)
            )
        }
    }
}

private fun blend(from: Color, to: Color, amount: Float): Color {
    val t = amount.coerceIn(0f, 1f)
    return Color(
        red = from.red + (to.red - from.red) * t,
        green = from.green + (to.green - from.green) * t,
        blue = from.blue + (to.blue - from.blue) * t,
        alpha = from.alpha + (to.alpha - from.alpha) * t
    )
}
